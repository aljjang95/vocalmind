def find_forward(hwp, text: str) -> bool:
    """현재 위치에서 전방으로 텍스트 찾기. 찾으면 True."""
    act = hwp.CreateAction('RepeatFind')
    pset = act.CreateSet()
    pset.SetItem('FindString', text)
    pset.SetItem('Direction', 0)
    pset.SetItem('IgnoreMessage', 1)
    return bool(act.Execute(pset))


def fill_cell(hwp, text: str):
    """현재 커서 위치의 테이블 셀 내용을 text로 교체."""
    hwp.Run('TableCellBlock')
    hwp.Run('Delete')
    lines = text.split('\n')
    for i, line in enumerate(lines):
        if i > 0:
            hwp.Run('BreakPara')
        if line:
            act = hwp.CreateAction('InsertText')
            pset = act.CreateSet()
            pset.SetItem('Text', line)
            act.Execute(pset)


